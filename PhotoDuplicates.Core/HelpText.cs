namespace PhotoDuplicates.Core
{
    public static class HelpText
    {
        public const string CommandLine =
@"Запуск: PhotoDuplicates.exe [папка] [параметры]
        PhotoDuplicates.ConsoleApp.exe [папка] [параметры]   (только отчёт, без окна)

Параметры:
  -f, --folder <папка>    папка с фотографиями
  -t, --threshold <0-32>  порог похожести: сколько битов dHash из 64 может отличаться
                          (по умолчанию 10; меньше - строже, больше - мягче)
  -r, --recursive         искать во вложенных папках
  --no-recursive          не заходить во вложенные папки
  -e, --exact-only        искать только точные копии (быстрее)
  -s, --similar           искать точные копии и похожие фото (по умолчанию)
  --no-cache              не использовать кеш хешей
  --clear-cache           очистить кеш перед поиском
  -o, --report <файл>     сохранить отчёт в текстовый файл
  -h, --help, /?          эта справка

Если указана папка, графическое приложение сразу начинает поиск.

Примеры:
  PhotoDuplicates.exe ""C:\Фото""
  PhotoDuplicates.ConsoleApp.exe ""C:\Фото"" -t 6 -o report.txt
  PhotoDuplicates.ConsoleApp.exe ""C:\Фото"" --exact-only --no-recursive";

        public const string Keys =
@"Горячие клавиши:
  F1        справка
  Ctrl+O    выбрать папку
  F5        начать поиск
  Esc       прервать поиск
  F6        отметить все дубликаты, кроме лучших файлов
  F7        снять все отметки
  Пробел    отметить / снять отметку с выбранного файла
  Del       удалить отмеченные файлы в корзину
  Ctrl+M    переместить отмеченные файлы в другую папку
  Ctrl+S    сохранить отчёт
  Ctrl+P    настройки
  Enter     открыть выбранный файл (также двойной щелчок)

Как читать результат:
  ★          лучший файл группы (больше разрешение / размер) - его предлагается оставить
  точные копии - файлы одинаковы байт в байт (одинаковый SHA-256)
  похожие    - одна и та же картинка, но уменьшенная, пересжатая или чуть изменённая
               (dHash отличается не больше чем на порог)";
    }
}
